def extract_custom_types(type_hint: Any) -> set[type]:
    """
    Рекурсивно извлекает все классы/типы из сложных аннотаций:
    Union[date, None], Optional[GenderType], list[Role] и т.д.
    """
    found: set[type] = set()
    origin = get_origin(type_hint)

    # Разворачиваем Mapped[T]
    if origin is Mapped:
        args = get_args(type_hint)
        if args:
            return extract_custom_types(args[0])
        return found

    # Если это составной тип (Union, Optional, list, dict, type1 | type2)
    if origin is not None:
        for arg in get_args(type_hint):
            found.update(extract_custom_types(arg))
        return found

    # Если это базовый тип данных/класс
    if isinstance(type_hint, type) and type_hint.__module__ != "builtins":
        found.add(type_hint)

    return found


def format_type_name(t: Any) -> str:
    """Форматирует строковое имя типа без лишних префиксов модуля."""
    origin = get_origin(t)

    # Обработка Mapped[T] -> форматируем T
    if origin is Mapped:
        args = get_args(t)
        return format_type_name(args[0]) if args else "Any"

    # Обработка Optional / Union / "|" синтаксиса
    if origin in (Union, types.UnionType):
        args = get_args(t)
        # Проверяем на pattern Optional (X | None)
        non_none_args = [a for a in args if a is not type(None)]
        is_optional = len(non_none_args) < len(args)

        inner_repr = " | ".join(format_type_name(a) for a in non_none_args)
        return f"{inner_repr} | None" if is_optional else inner_repr

    if isinstance(t, type):
        return t.__name__

    return str(t).replace("typing.", "")


def generate_typeddicts(
    base_class: type[DeclarativeBase], output_path: str | Path = "generated_schemas.py"
) -> None:
    models = [
        cls
        for cls in base_class.__subclasses__()
        if hasattr(cls, "__tablename__") and cls.__tablename__ is not None
    ]

    needed_imports: dict[str, set[str]] = {}
    class_definitions: list[str] = []

    for model in models:
        type_hints = get_type_hints(model)
        mapper = sa_inspect(model)

        class_lines = [f"class {model.__name__}CreateDict(TypedDict):"]
        fields_written = False

        for col in mapper.columns:
            # Пропускаем автоинкрементный ID
            if col.primary_key and col.autoincrement:
                continue

            attr_name = col.key
            hint = type_hints.get(attr_name, Any)

            # Собираем все зависимые типы (date, GenderType, etc.)
            for custom_type in extract_custom_types(hint):
                mod_name = custom_type.__module__
                type_name = custom_type.__name__
                needed_imports.setdefault(mod_name, set()).add(type_name)

            type_repr = format_type_name(hint)

            # Проверка на опциональность (nullable или наличие дефолта)
            has_default = (col.default is not None) or (col.server_default is not None)
            is_optional = col.nullable or has_default

            if is_optional:
                class_lines.append(f"    {attr_name}: NotRequired[{type_repr}]")
            else:
                class_lines.append(f"    {attr_name}: {type_repr}")

            fields_written = True

        if not fields_written:
            class_lines.append("    pass")

        class_definitions.append("\n".join(class_lines))

    # Формируем заголовочную секцию импортов
    header_lines = [
        "# AUTOGENERATED FILE. DO NOT EDIT DIRECTLY.",
        "from __future__ import annotations",
        "from typing import TypedDict, NotRequired, Optional, Any",
    ]

    # Добавляем обнаруженные импорты модулей
    for module_path, names in sorted(needed_imports.items()):
        names_str = ", ".join(sorted(names))
        header_lines.append(f"from {module_path} import {names_str}")

    header_lines.append("")  # пустая строка

    full_output = (
        "\n".join(header_lines) + "\n\n" + "\n\n".join(class_definitions) + "\n"
    )
    out_path = Path(output_path)

    # Проверяем наличие директории
    if not out_path.parent.exists():
        out_path.parent.mkdir(parents=True)
    out_path.write_text(full_output, encoding="utf-8")
    print(f"✅ Успешно сгенерировано {len(models)} схем в файл: {output_path}")


if __name__ == "__main__":
    path = Path(__file__).parent.parent / "models" / "database" / "dto" / "dto.py"

    generate_typeddicts(Base, output_path=path)
